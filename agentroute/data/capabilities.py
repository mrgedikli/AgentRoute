def class_names():
    return [name for name, _, _ in CLASSES]


def capability_cards():
    """Two capability cards per class, as (class_id, variant_id, sentences).

    A card is one description plus two example requests. Two variants model
    two different providers describing the same skill in different words.
    """
    rows = []
    for class_id, (name, descs, _) in enumerate(CLASSES):
        ex = EXAMPLES[name]
        rows.append((class_id, 0, [descs[0], ex[0], ex[1]]))
        rows.append((class_id, 1, [descs[1], ex[1], ex[2]]))
    return rows


def class_sentences():
    """All five capability sentences of each class: two descriptions + three examples.

    Every agent mixes these with its own random weights (v2), so that no two
    agents advertise the same capability vector.
    """
    return [list(descs) + list(EXAMPLES[name]) for name, descs, _ in CLASSES]


def split_intents(n_test=3, seed=0):
    """Split the ten intents of each class into train and test sets.

    Returns two lists of (class_id, text). The split is fixed by the seed so
    that the DQN is never trained on the requests used for evaluation.
    """
    rng = random.Random(seed)
    train, test = [], []
    for class_id, (_, _, intents) in enumerate(CLASSES):
        order = list(range(len(intents)))
        rng.shuffle(order)
        for i, idx in enumerate(order):
            if i < n_test:
                test.append((class_id, intents[idx]))
            else:
                train.append((class_id, intents[idx]))
    return train, test
